#include "textflag.h"

// func fastConv4x24(y *float32, ystride uintptr, x *float32, xoff *int32, w *float32, bias *float32, steps, wcol, wstep uintptr)
// Computes a 4 output-channel x 24 frame tile of a direct convolution:
// y[c*ystride+t] = bias[c] + sum_j x[xoff[j]+t] * w[c*wcol+j*wstep].
TEXT ·fastConv4x24(SB), NOSPLIT, $0-72
	MOVQ y+0(FP), DI
	MOVQ ystride+8(FP), R8
	SHLQ $2, R8
	MOVQ x+16(FP), SI
	MOVQ xoff+24(FP), BX
	MOVQ w+32(FP), DX
	MOVQ bias+40(FP), CX
	MOVQ steps+48(FP), R9
	MOVQ wcol+56(FP), R11
	SHLQ $2, R11
	MOVQ wstep+64(FP), R12
	SHLQ $2, R12
	LEAQ (DX)(R11*2), R13
	VBROADCASTSS 0(CX), Y0
	VMOVAPS Y0, Y1
	VMOVAPS Y0, Y2
	VBROADCASTSS 4(CX), Y3
	VMOVAPS Y3, Y4
	VMOVAPS Y3, Y5
	VBROADCASTSS 8(CX), Y6
	VMOVAPS Y6, Y7
	VMOVAPS Y6, Y8
	VBROADCASTSS 12(CX), Y9
	VMOVAPS Y9, Y10
	VMOVAPS Y9, Y11
loop:
	MOVLQSX (BX), AX
	LEAQ (SI)(AX*4), R10
	VMOVUPS (R10), Y12
	VMOVUPS 32(R10), Y13
	VMOVUPS 64(R10), Y14
	VBROADCASTSS (DX), Y15
	VFMADD231PS Y12, Y15, Y0
	VFMADD231PS Y13, Y15, Y1
	VFMADD231PS Y14, Y15, Y2
	VBROADCASTSS (DX)(R11*1), Y15
	VFMADD231PS Y12, Y15, Y3
	VFMADD231PS Y13, Y15, Y4
	VFMADD231PS Y14, Y15, Y5
	VBROADCASTSS (R13), Y15
	VFMADD231PS Y12, Y15, Y6
	VFMADD231PS Y13, Y15, Y7
	VFMADD231PS Y14, Y15, Y8
	VBROADCASTSS (R13)(R11*1), Y15
	VFMADD231PS Y12, Y15, Y9
	VFMADD231PS Y13, Y15, Y10
	VFMADD231PS Y14, Y15, Y11
	ADDQ $4, BX
	ADDQ R12, DX
	ADDQ R12, R13
	DECQ R9
	JNZ loop
	VMOVUPS Y0, (DI)
	VMOVUPS Y1, 32(DI)
	VMOVUPS Y2, 64(DI)
	ADDQ R8, DI
	VMOVUPS Y3, (DI)
	VMOVUPS Y4, 32(DI)
	VMOVUPS Y5, 64(DI)
	ADDQ R8, DI
	VMOVUPS Y6, (DI)
	VMOVUPS Y7, 32(DI)
	VMOVUPS Y8, 64(DI)
	ADDQ R8, DI
	VMOVUPS Y9, (DI)
	VMOVUPS Y10, 32(DI)
	VMOVUPS Y11, 64(DI)
	VZEROUPPER
	RET
